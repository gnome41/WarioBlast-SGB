/* Ahead-of-time recompiler for the developer build: ROM -> gen_bank_NN.c
 * and gen_table.c, linked statically into warioblast.  (The release player
 * runs the same recompiler at runtime instead; see runtime/native.c.)
 *
 * usage: wb_recomp ROM OUTDIR [BANK_FILES] */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "recomp.h"

static const char HEADER[] = "/* generated by tools/recomp - do not edit */\n#include \"cpu_ops.h\"\n\n";

static char *read_all(const char *path, size_t *n)
{
    FILE *f = fopen(path, "rb");
    if (!f)
        return NULL;
    fseek(f, 0, SEEK_END);
    long size = ftell(f);
    fseek(f, 0, SEEK_SET);
    char *d = size >= 0 ? malloc((size_t)size + 1) : NULL;
    if (d && fread(d, 1, (size_t)size, f) != (size_t)size) {
        free(d);
        d = NULL;
    }
    fclose(f);
    if (d)
        *n = (size_t)size;
    return d;
}

/* Only rewrites files whose contents changed, to avoid needless rebuilds. */
static int write_if_changed(const char *path, const char *text, size_t n)
{
    size_t old_n;
    char *old = read_all(path, &old_n);
    bool same = old && old_n == n && !memcmp(old, text, n);
    free(old);
    if (same)
        return 0;
    FILE *f = fopen(path, "wb");
    if (!f || fwrite(text, 1, n, f) != n) {
        fprintf(stderr, "wb_recomp: cannot write %s\n", path);
        if (f)
            fclose(f);
        return 1;
    }
    return fclose(f) != 0;
}

typedef struct { char *p; size_t len, cap; } Buf;

static void add(Buf *b, const char *s, size_t n)
{
    if (b->len + n + 1 > b->cap) {
        b->cap = (b->len + n + 1) * 2;
        b->p = realloc(b->p, b->cap);
    }
    memcpy(b->p + b->len, s, n);
    b->len += n;
    b->p[b->len] = 0;
}

static void adds(Buf *b, const char *s) { add(b, s, strlen(s)); }

int main(int argc, char **argv)
{
    if (argc < 3) {
        fprintf(stderr, "usage: %s ROM OUTDIR [BANK_FILES]\n", argv[0]);
        return 2;
    }
    size_t size;
    uint8_t *rom = (uint8_t *)read_all(argv[1], &size);
    if (!rom) {
        fprintf(stderr, "wb_recomp: cannot read %s\n", argv[1]);
        return 1;
    }
    unsigned files = argc > 3 ? (unsigned)atoi(argv[3]) : (unsigned)(size / 0x4000);
    RecompResult r;
    if (!recomp_run(rom, size, &game_notes, &r)) {
        fprintf(stderr, "wb_recomp: not a usable ROM image\n");
        return 1;
    }

    int err = 0;
    char path[4096], line[128];
    uint32_t f = 0;
    for (unsigned b = 0; b < files; b++) {
        Buf out = { 0 };
        adds(&out, HEADER);
        for (; f < r.nfuncs && r.funcs[f].bank == b; f++) {
            add(&out, r.src + r.funcs[f].src_off, r.funcs[f].src_len);
            adds(&out, "\n");
        }
        snprintf(path, sizeof path, "%s/gen_bank_%02u.c", argv[2], b);
        err |= write_if_changed(path, out.p, out.len);
        free(out.p);
    }

    Buf t = { 0 };
    adds(&t, HEADER);
    for (uint32_t i = 0; i < r.nfuncs; i++) {
        char name[16];
        recomp_fn_name(r.funcs[i].bank, r.funcs[i].entry, name);
        snprintf(line, sizeof line, "void %s(void);\n", name);
        adds(&t, line);
    }
    adds(&t, "\nconst GenEntry gen_static_entries[] = {\n");
    for (size_t i = 0; i < r.nentries; i++) {
        char name[16];
        const RecompFunc *fn = &r.funcs[r.entries[i].fn];
        recomp_fn_name(fn->bank, fn->entry, name);
        snprintf(line, sizeof line, "    { %u, 0x%04x, %s },\n", r.entries[i].bank, r.entries[i].addr, name);
        adds(&t, line);
    }
    if (!r.nentries)
        adds(&t, "    { 0, 0, 0 },\n");
    snprintf(line, sizeof line, "};\nconst size_t gen_static_count = %zu;\n", r.nentries);
    adds(&t, line);
    snprintf(path, sizeof path, "%s/gen_table.c", argv[2]);
    err |= write_if_changed(path, t.p, t.len);
    free(t.p);

    printf("recomp: %u functions, %zu instructions, %zu jump tables, %zu coverage seeds added\n",
           r.nfuncs, r.ninsns, r.ntables, r.nseeds);
    recomp_free(&r);
    free(rom);
    return err;
}
