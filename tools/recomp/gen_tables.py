#!/usr/bin/env python3
"""Build-time generators.  None of the outputs contain anything from the
ROM: the opcode table and interpreter come from sm83.py, the game notes
from overrides.toml and coverage.txt (addresses and hints only).

usage: gen_tables.py --out DIR --runtime DIR [--config overrides.toml] [--coverage coverage.txt]

Writes:
  interp_ops.inc   fallback interpreter switch
  sm83_table.c     opcode table used by the C recompiler
  game_data.c      game notes: analysis hints, coverage seeds, expected ROM CRC
  tcc_prelude.c    C prelude for recompiling at runtime with TinyCC
"""

import argparse
import os
import sys
import tomllib

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import sm83  # noqa: E402

HEADER = "/* generated by tools/recomp/gen_tables.py - do not edit */\n"

KINDS = ["op", "jp", "jr", "call", "ret", "reti", "rst", "jphl", "halt", "stop",
         "ei", "di", "illegal"]


def write_if_changed(path, text):
    try:
        with open(path) as f:
            if f.read() == text:
                return
    except FileNotFoundError:
        pass
    with open(path, "w") as f:
        f.write(text)


def c_str(s):
    if s is None:
        return "NULL"
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


# ------------------------------------------------------------ interpreter

def fill(template, n8, n16, e8):
    return template.replace("{n8}", n8).replace("{n16}", n16).replace("{e8}", e8)


def interp_body(op, length):
    """C statements for one opcode in the interpreter (pc = its address)."""
    k = op.kind
    nxt = f"(uint16_t)(pc + {length})"
    cond = op.cond
    if k == "op":
        code = fill(op.code, "n8", "n16", "(int8_t)n8")
        return f"R.pc = {nxt}; {code} TICK({op.cycles});"
    if k in ("jp", "jr"):
        tgt = "n16" if k == "jp" else "(uint16_t)(pc + 2 + (int8_t)n8)"
        if cond:
            return (f"if ({cond}) {{ R.pc = {tgt}; TICK({op.cycles_taken}); }} "
                    f"else {{ R.pc = {nxt}; TICK({op.cycles}); }}")
        return f"R.pc = {tgt}; TICK({op.cycles});"
    if k == "call":
        if cond:
            return (f"if ({cond}) {{ push16({nxt}); R.pc = n16; TICK({op.cycles_taken}); }} "
                    f"else {{ R.pc = {nxt}; TICK({op.cycles}); }}")
        return f"push16({nxt}); R.pc = n16; TICK({op.cycles});"
    if k == "ret":
        if cond:
            return (f"if ({cond}) {{ R.pc = pop16(); TICK({op.cycles_taken}); }} "
                    f"else {{ R.pc = {nxt}; TICK({op.cycles}); }}")
        return f"R.pc = pop16(); TICK({op.cycles});"
    if k == "reti":
        return f"R.pc = pop16(); R.ime = 1; TICK({op.cycles});"
    if k == "rst":
        return f"push16({nxt}); R.pc = {op.target:#06x}; TICK({op.cycles});"
    if k == "jphl":
        return f"R.pc = HL; TICK({op.cycles});"
    if k == "halt":
        return f"R.pc = {nxt}; TICK({op.cycles}); gb_halt();"
    if k == "stop":
        return f"R.pc = {nxt}; TICK({op.cycles}); gb_stop();"
    if k == "di":
        return f"R.pc = {nxt}; R.ime = 0; R.ei_delay = 0; TICK({op.cycles});"
    if k == "ei":
        return f"R.pc = {nxt}; if (!R.ime) {{ R.ei_delay = 1; }} TICK({op.cycles});"
    if k == "illegal":
        return "gb_illegal(pc);"
    raise ValueError(k)


def gen_interp():
    out = ["/* generated by tools/recomp - do not edit */", "switch (op) {"]
    for o in range(256):
        if o == 0xCB:
            out.append("case 0xCB: {")
            out.append("    uint8_t cb = RD(pc + 1);")
            out.append("    switch (cb) {")
            for c in range(256):
                out.append(f"    case {c:#04x}: {{ {interp_body(sm83.CB[c], 2)} }} return;")
            out.append("    }")
            out.append("    return;")
            out.append("}")
            continue
        op = sm83.MAIN[o]
        pre = ""
        if op.length == 2:
            pre = "uint8_t n8 = RD(pc + 1); (void)n8; "
        if op.length == 3:
            pre = "uint16_t n16 = RD(pc + 1) | (RD(pc + 2) << 8); "
        out.append(f"case {o:#04x}: {{ {pre}{interp_body(op, op.length)} }} return;")
    out.append("}")
    return "\n".join(out) + "\n"


# ------------------------------------------------------------ opcode table

def op_row(op):
    kind = KINDS.index(op.kind)
    return (f"    {{ {op.length}, {kind}, {op.cycles}, {op.cycles_taken}, "
            f"{op.target if op.target is not None else 0}, {int(op.sets_a)}, "
            f"{c_str(op.mnem)}, {c_str(op.code if op.kind == 'op' else None)}, {c_str(op.cond)} }},")


def gen_sm83_table():
    out = [HEADER, '#include "recomp.h"\n\n', "const Sm83Op sm83_main[256] = {\n"]
    for o in range(256):
        if o == 0xCB:
            out.append('    { 2, K_PREFIX, 0, 0, 0, 0, "prefix cb", NULL, NULL },\n')
        else:
            out.append(op_row(sm83.MAIN[o]) + "\n")
    out.append("};\n\nconst Sm83Op sm83_cb[256] = {\n")
    for o in range(256):
        out.append(op_row(sm83.CB[o]) + "\n")
    out.append("};\n")
    return "".join(out)


# ------------------------------------------------------------ game notes

def parse_ref(s):
    if ":" in s:
        b, a = s.split(":")
        b, a = int(b, 16), int(a, 16)
    else:
        b, a = 0, int(s, 16)
    return (0 if a < 0x4000 else b), a


PAIRS = ["bc", "de", "hl"]
REGS = ["b", "c", "d", "e", "h", "l", "", "a"]


def gen_game_data(cfg, coverage):
    def u16_list(name, vals):
        body = ", ".join(f"{v:#06x}" for v in vals) or "0"
        return f"static const uint16_t {name}[] = {{ {body} }};\n"

    def ref_list(name, refs):
        body = "".join(f"    {{ {b}, {a:#06x} }},\n" for b, a in refs) or "    { 0, 0 },\n"
        return f"static const RecompRef {name}[] = {{\n{body}}};\n"

    noret = [parse_ref(s) for s in cfg.get("noreturn", [])]
    entries = [parse_ref(s) for s in cfg.get("entries", [])]
    far = cfg.get("far_tables", [])
    fcalls = cfg.get("far_calls", [])
    cov = sorted(set(coverage))
    crc = int(str(cfg["rom_crc32"]), 0) if "rom_crc32" in cfg else 0
    audio = cfg.get("audio", {})
    wide = cfg.get("wide", {})
    out = [HEADER, '#include "recomp.h"\n\n',
           u16_list("jump_table_routines", cfg.get("jump_table_routines", [])),
           u16_list("bank_switch_routines", cfg.get("bank_switch_routines", [])),
           ref_list("noreturn", noret), ref_list("extra_entries", entries),
           ref_list("coverage", cov),
           "static const RecompFarTable far_tables[] = {\n",
           "".join(f"    {{ {int(t['addr'], 16):#06x}, {t.get('max', 256)} }},\n" for t in far) or "    { 0, 0 },\n",
           "};\n\n",
           "static const RecompFarCall far_calls[] = {\n",
           "".join(f"    {{ {int(c['addr'], 16):#06x}, {PAIRS.index(c['addr_reg'])}, "
                   f"{REGS.index(c['bank_reg']) if c.get('bank_reg') else -1} }},\n" for c in fcalls)
           or "    { 0, 0, -1 },\n",
           "};\n\n",
           "#define N(a) (sizeof a / sizeof a[0])\n",
           "const RecompConfig game_notes = {\n",
           f"    {crc:#010x}u,\n",
           f"    jump_table_routines, {len(cfg.get('jump_table_routines', []))},\n",
           f"    bank_switch_routines, {len(cfg.get('bank_switch_routines', []))},\n",
           f"    noreturn, {len(noret)},\n",
           f"    extra_entries, {len(entries)},\n",
           f"    far_tables, {len(far)},\n",
           f"    far_calls, {len(fcalls)},\n",
           f"    coverage, {len(cov)},\n",
           "};\n\n",
           "const GameAudioNotes game_audio = {\n",
           "".join(f"    {int(audio.get(k, 0)):#06x},\n" for k in
                   ("music_request", "sfx_request", "sfx_channel_mask", "pause_flag",
                    "pause_mask", "music_stop", "ack_mask")),
           "};\n\n",
           "const GameWideNotes game_wide = {\n",
           "".join(f"    {int(wide.get(k, 0)):#06x},\n" for k in
                   ("active_wx", "active_wy", "arena_width", "arena_height")),
           "};\n"]
    return "".join(out)


# ------------------------------------------------------------ TinyCC prelude

CHKSTK = r'''#ifdef _WIN64
/* Win64 stack probe as called by TinyCC's function prologue: builds the
 * frame (push rbp; mov rsp,rbp) and reserves EAX bytes, touching each
 * 4 KiB page in order so the guard page is hit. */
__asm__(
    ".globl __chkstk\n"
    "__chkstk:\n"
    "    pop %r11\n"
    "    push %rbp\n"
    "    mov %rsp,%rbp\n"
    "    mov %eax,%eax\n"
    ".Lchk_loop:\n"
    "    cmp $4096,%rax\n"
    "    jb .Lchk_last\n"
    "    sub $4096,%rsp\n"
    "    orl $0,(%rsp)\n"
    "    sub $4096,%rax\n"
    "    jmp .Lchk_loop\n"
    ".Lchk_last:\n"
    "    sub %rax,%rsp\n"
    "    orl $0,(%rsp)\n"
    "    jmp *%r11\n");
#endif
'''

PRELUDE_TYPES = '''typedef unsigned char uint8_t;
typedef signed char int8_t;
typedef unsigned short uint16_t;
typedef short int16_t;
typedef unsigned int uint32_t;
typedef int int32_t;
typedef unsigned long long uint64_t;
typedef long long int64_t;
typedef __SIZE_TYPE__ size_t;
typedef _Bool bool;
#define true 1
#define false 0
#define NULL ((void *)0)
#define offsetof(t, m) ((size_t)&((t *)0)->m)
'''

# The compiled code makes no external references: runtime symbols are
# reached through pointers defined here and filled in by the host.
BINDINGS = '''#define gb (*wb_gb)
#define trace_enabled (*wb_trace_enabled)
#define mem_read (*wb_mem_read)
#define mem_write (*wb_mem_write)
#define gb_tick (*wb_gb_tick)
#define gb_halt (*wb_gb_halt)
#define gb_stop (*wb_gb_stop)
#define gb_illegal (*wb_gb_illegal)
#define trace_insn (*wb_trace_insn)
'''

LAYOUT = '''
/* struct layout probe, compared with the host compiler's at load time */
size_t wb_layout(int i)
{
    switch (i) {
    case 0: return sizeof(Gb);
    case 1: return offsetof(Gb, cpu);
    case 2: return offsetof(Gb, rom_bank);
    case 3: return offsetof(Gb, io);
    case 4: return offsetof(Gb, ie);
    case 5: return offsetof(Gb, cycles);
    case 6: return sizeof(Cpu);
    }
    return 0;
}
'''


def strip_includes(text):
    return "\n".join(l for l in text.splitlines() if not l.startswith("#include")) + "\n"


def gen_prelude(runtime):
    with open(os.path.join(runtime, "gb.h")) as f:
        gb_h = strip_includes(f.read())
    with open(os.path.join(runtime, "cpu_ops.h")) as f:
        ops_h = strip_includes(f.read())
    text = (CHKSTK + PRELUDE_TYPES + BINDINGS + gb_h +
            "Gb *wb_gb;\nbool *wb_trace_enabled;\n" + ops_h + LAYOUT)
    return HEADER + "const char tcc_prelude[] =\n" + "\n".join(
        "    " + c_str(line + "\n") for line in text.splitlines()) + ";\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--runtime", required=True)
    ap.add_argument("--config")
    ap.add_argument("--coverage")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    cfg = {}
    if a.config:
        with open(a.config, "rb") as f:
            cfg = tomllib.load(f)
    cov = []
    if a.coverage and os.path.exists(a.coverage):
        with open(a.coverage) as f:
            cov = [parse_ref(l.strip()) for l in f if l.strip() and not l.startswith("#")]
    write_if_changed(os.path.join(a.out, "interp_ops.inc"), gen_interp())
    write_if_changed(os.path.join(a.out, "sm83_table.c"), gen_sm83_table())
    write_if_changed(os.path.join(a.out, "game_data.c"), gen_game_data(cfg, cov))
    write_if_changed(os.path.join(a.out, "tcc_prelude.c"), gen_prelude(a.runtime))


if __name__ == "__main__":
    main()
